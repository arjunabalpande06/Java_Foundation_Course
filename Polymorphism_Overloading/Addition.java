
public class Addition {
	public void add()
	{
		int a = 20,b = 30;
		int c = a+b;
		System.out.println("Addition is : "+c);
	}
	
	public void add(int x)
	{
		int a = x,b = x;
		int c = a+b;
		System.out.println("Addition is : "+c);
	}
	
	public void add(int x, int y)
	{
		int a = x,b = y;
		int c = a+b;
		System.out.println("Addition is : "+c);
	}
}
